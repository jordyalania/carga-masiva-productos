"""Export executable psql scripts from the same versioned SQL used by .NET."""
from pathlib import Path
import re
import textwrap

root = Path(__file__).resolve().parents[1]
src = root / 'backend' / 'src'
out = root / 'backend' / 'database'
out.mkdir(exist_ok=True)
shared = (src / 'Shared' / 'Platform.cs').read_text()
outbox = re.search(r'public const string OutboxSql = """(.*?)""";', shared, re.S)
assert outbox
migrations = [('outbox-v1', textwrap.dedent(outbox[1]).strip())]
for service in ['Auth', 'Control', 'Importer', 'Notifier']:
    text = (src / service / 'Program.cs').read_text()
    for name, sql in re.findall(r'Migrate\("([a-z0-9-]+)", """(.*?)"""\)', text, re.S):
        migrations.append((name, textwrap.dedent(sql).strip()))
head = '''-- Generated by scripts/export_migrations.py. Run with psql -v ON_ERROR_STOP=1.
-- Uses the same migration ledger as application startup; does not seed passwords.
CREATE SCHEMA IF NOT EXISTS platform;
CREATE TABLE IF NOT EXISTS platform.migrations(name text PRIMARY KEY, applied_at timestamptz NOT NULL DEFAULT now());
'''
for name, sql in migrations:
    head += f'''\nBEGIN;
SELECT pg_advisory_xact_lock(790001);
SELECT EXISTS(SELECT 1 FROM platform.migrations WHERE name='{name}') AS applied \\gset
\\if :applied
\\else
{sql}
INSERT INTO platform.migrations(name) VALUES ('{name}');
\\endif
COMMIT;
'''
(out / 'migrate.sql').write_text(head)
print('Exported', len(migrations), 'versioned SQL migrations.')
